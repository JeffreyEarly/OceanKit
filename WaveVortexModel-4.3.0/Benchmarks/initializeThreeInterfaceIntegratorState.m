function [state,evidence] = initializeThreeInterfaceIntegratorState(wvt,seed,options)
% Initialize the deterministic physical state for the integrator benchmark.
arguments
    wvt WVTransformConstantStratification {mustBeNonempty}
    seed (1,1) double {mustBeInteger,mustBeNonnegative}
    options.gmEnergyLevel (1,1) double {mustBePositive} = 1
    options.geostrophicMaximumSpeed (1,1) double {mustBePositive} = 0.15
    options.rollOffMode (1,1) double {mustBeInteger,mustBePositive} = 4
    options.transitionMode (1,1) double {mustBeInteger,mustBePositive} = 16
end
if options.transitionMode <= options.rollOffMode
    error("WaveVortexBenchmark:InvalidPhysicalSpectrum","The geostrophic transition mode must exceed the roll-off mode.")
end

rng(seed,"twister");
wvt.removeAll();
wvt.initWithGMSpectrum(GMAmplitude=options.gmEnergyLevel,shouldOnlyRandomizeOrientations=true);
ApWave = wvt.Ap;
AmWave = wvt.Am;
wvt.A0 = 0*wvt.A0;
uWave = wvt.u;
vWave = wvt.v;
wWave = wvt.w;

deltaK = wvt.kRadial(2)-wvt.kRadial(1);
kRollOff = options.rollOffMode*deltaK;
kTransition = options.transitionMode*deltaK;
spectrum = @(k,j)firstBaroclinicRedSpectrum(k,j,kRollOff,kTransition);
[~,~,A0Shape] = wvt.geostrophicComponent.randomAmplitudesWithSpectrum(A0Spectrum=spectrum,shouldOnlyRandomizeOrientations=true);
wvt.Ap = 0*wvt.Ap;
wvt.Am = 0*wvt.Am;
wvt.A0 = A0Shape;
geostrophicShapeSpeedMaximum = wvt.uvMax;
if ~isfinite(geostrophicShapeSpeedMaximum) || geostrophicShapeSpeedMaximum <= 0
    error("WaveVortexBenchmark:InvalidPhysicalSpectrum","The geostrophic spectrum did not produce a finite nonzero velocity field.")
end
geostrophicScale = options.geostrophicMaximumSpeed/geostrophicShapeSpeedMaximum;

wvt.Ap = ApWave;
wvt.Am = AmWave;
wvt.A0 = geostrophicScale*A0Shape;
combinedHorizontalSpeed = sqrt(wvt.u.^2+wvt.v.^2);
positiveWave = abs([wvt.Ap(:); wvt.Am(:)]);
positiveWave = positiveWave(positiveWave>0);
positiveVortex = abs(wvt.A0(:));
positiveVortex = positiveVortex(positiveVortex>0);
state = struct("t0",wvt.t,"Ap",wvt.Ap,"Am",wvt.Am,"A0",wvt.A0);
evidence = struct( ...
    "id","gm1-red-geostrophic-j1-v1", ...
    "seed",seed, ...
    "gmEnergyLevel",options.gmEnergyLevel, ...
    "gmAmplitudePolicy","exact spectrum amplitudes with deterministic random orientations", ...
    "geostrophicVerticalMode",1, ...
    "geostrophicSpectrum","k^(3/2) below k_r, k^(-5/3) from k_r through k_f, and k_f^(4/3) k^(-3) above k_f", ...
    "geostrophicMaximumSpeedTarget",options.geostrophicMaximumSpeed, ...
    "geostrophicHorizontalSpeedMaximum",geostrophicScale*geostrophicShapeSpeedMaximum, ...
    "geostrophicScale",geostrophicScale, ...
    "deltaK",deltaK, ...
    "rollOffMode",options.rollOffMode, ...
    "transitionMode",options.transitionMode, ...
    "kRollOff",kRollOff, ...
    "kTransition",kTransition, ...
    "rollOffWavelength",2*pi/kRollOff, ...
    "transitionWavelength",2*pi/kTransition, ...
    "waveHorizontalSpeedMaximum",max(sqrt(uWave.^2+vWave.^2),[],"all"), ...
    "waveVerticalSpeedMaximum",max(abs(wWave),[],"all"), ...
    "combinedHorizontalSpeedMaximum",max(combinedHorizontalSpeed,[],"all"), ...
    "combinedHorizontalSpeedRMS",sqrt(mean(combinedHorizontalSpeed.^2,"all")), ...
    "combinedVerticalSpeedMaximum",max(abs(wvt.w),[],"all"), ...
    "waveEnergy",wvt.waveEnergy, ...
    "geostrophicEnergy",wvt.geostrophicEnergy, ...
    "waveCoefficientMinimum",min(positiveWave), ...
    "waveCoefficientMedian",median(positiveWave), ...
    "waveCoefficientMaximum",max(positiveWave), ...
    "vortexCoefficientMinimum",min(positiveVortex), ...
    "vortexCoefficientMedian",median(positiveVortex), ...
    "vortexCoefficientMaximum",max(positiveVortex));
end

function value = firstBaroclinicRedSpectrum(k,j,kRollOff,kTransition)
x = k/kRollOff;
transitionRatio = kTransition/kRollOff;
value = zeros(size(k));
low = k < kRollOff;
middle = k >= kRollOff & k <= kTransition;
high = k > kTransition;
value(low) = x(low).^(3/2);
value(middle) = x(middle).^(-5/3);
value(high) = transitionRatio^(4/3)*x(high).^(-3);
value = value.*double(j==1);
end
