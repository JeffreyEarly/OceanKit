function manifest = writeBoussinesqVariableModelAdoptionFixture(folder,screeningFolder,options)
% Build one Boussinesq-256 full-model fixture from the saved modal source.
arguments (Input)
    folder (1,1) string
    screeningFolder (1,1) string {mustBeFolder}
    options.numericalSourceRoot (1,1) string {mustBeFolder}
end
arguments (Output)
    manifest (1,1) struct
end

assert(~isfolder(folder),"Refusing to overwrite a fixture directory.");
assert(startsWith(string(which("WVModel")),options.numericalSourceRoot), ...
    "WaveVortexModel:FixtureSource","MATLAB is not using the declared numerical source root.");
folder = string(java.io.File(char(folder)).getCanonicalPath());
screeningFolder = string(java.io.File(char(screeningFolder)).getCanonicalPath());
usableBefore = double(java.io.File(char(fileparts(folder))).getUsableSpace());
physicalMemoryBytes = hostPhysicalMemoryBytes();
minimumFreeBytes = 8*2^30;
assert(usableBefore>=minimumFreeBytes,"WaveVortexModel:FixtureCapacity", ...
    "Boussinesq fixture authoring requires at least 8 GiB free.");
mkdir(folder);

screeningManifestPath = fullfile(screeningFolder,"manifest.json");
screening = jsondecode(fileread(screeningManifestPath));
assert(string(screening.schema)=="wvm-variable-screening-fixtures-v1" && ...
    numel(screening.cases)==1,"WaveVortexModel:FixtureInput", ...
    "Expected one frozen variable-screening fixture.");
saved = screening.cases(1);
assert(string(saved.family)=="boussinesq" && ...
    isequal(double(saved.grid(:)).',[256 256 129]) && ...
    sha256(saved.sourcePath)==string(saved.sourceSHA256), ...
    "WaveVortexModel:FixtureInput","The saved Boussinesq-256 source differs.");

[wvt,reader] = WVTransform.waveVortexTransformFromFile(char(saved.sourcePath), ...
    iTime=Inf,shouldReadOnly=true);
reader.close();
assert(isa(wvt,"WVTransformBoussinesq") && wvt.t==saved.t && wvt.t0==saved.t0, ...
    "WaveVortexModel:FixtureInput","The restored Boussinesq state differs.");
initialTime = wvt.t;
finalTime = initialTime+.5;
denseTime = initialTime+.25;
step = .5;
model = WVModel(wvt);
model.eulerianObservingSystem.addNetCDFOutputVariables("u");
model.setFloatPositions([1900 11400],[1100 7700],[-250 -750],'u');
phi = sin(2*pi*wvt.X/wvt.Lx).*cos(2*pi*wvt.Y/wvt.Ly);
model.addTracer(phi,"dye");

identity = "variable-boussinesq-composite-256";
sourcePath = fullfile(folder,identity+"-source.nc");
referencePath = fullfile(folder,identity+"-matlab-reference.nc");
writeInitial(model,sourcePath,initialTime,finalTime,denseTime);
model.closeNetCDFFile();
clear model wvt
copyfile(sourcePath,referencePath);
reference = WVModel.modelFromFile(referencePath);
reference.outputTimesForIntegrationPeriod(initialTime,finalTime);
reference.setupIntegrator(integratorType="fixed",deltaT=step);
reference.integrateToTime(finalTime,shouldShowIntegrationDiagnostics=false,callback=@(~)[]);
reference.closeNetCDFFile();
clear reference

assert(isequal(ncread(referencePath,"/wave-vortex/t"),[initialTime;finalTime]) && ...
    isequal(ncread(referencePath,"/dense/t"),denseTime) && ...
    isequal(ncread(referencePath,"/particles/t"),[initialTime;finalTime]) && ...
    isequal(ncread(referencePath,"/tracers/t"),[initialTime;finalTime]), ...
    "WaveVortexModel:FixtureSchedule","Unexpected Boussinesq output times.");
sourceInfo = dir(sourcePath);
referenceInfo = dir(referencePath);
[status,numericalHead] = system("git -C "+shellQuote(options.numericalSourceRoot)+" rev-parse HEAD");
assert(status==0);
generatorPath = string(mfilename("fullpath"))+".m";
generatorRoot = string(fileparts(fileparts(fileparts(fileparts(generatorPath)))));
[status,generatorHead] = system("git -C "+shellQuote(generatorRoot)+" rev-parse HEAD");
assert(status==0);
realVolumeBytes = 256*256*129*8;
modalComplexBytes = saved.Nj*saved.Nkl*16;
profile = struct(id=identity,family="boussinesq",grid=[256 256 129], ...
    Nj=saved.Nj,Nkl=saved.Nkl,initialTime=initialTime,finalTime=finalTime, ...
    sourcePath=sourcePath,referencePath=referencePath, ...
    sourceSHA256=sha256(sourcePath),referenceSHA256=sha256(referencePath), ...
    sourceBytes=sourceInfo.bytes,referenceBytes=referenceInfo.bytes, ...
    expectedStepCount=1,expectedRHSEvaluationCount=4, ...
    expectedCoefficientRecords=2,expectedDenseRecords=1, ...
    expectedParticleRecords=2,expectedTracerRecords=2, ...
    capabilities=struct(fullXYZTracer=true,tracerAdvection="three-dimensional-xyz", ...
        movingParticles=true,denseEulerianU=true), ...
    capacityEstimate=struct(realVolumeBytes=realVolumeBytes, ...
        modalComplexBytes=modalComplexBytes,coefficientFamilyCount=3, ...
        coefficientRecordBytes=3*modalComplexBytes, ...
        outputPayloadLowerBoundBytes=2*(3*modalComplexBytes+realVolumeBytes)+3*realVolumeBytes));
manifest = struct(schema="wvm-variable-boussinesq-model-fixture-256-v1", ...
    generatorPath=generatorPath,generatorSHA256=sha256(generatorPath), ...
    generatorHEAD=strtrim(string(generatorHead)), ...
    numericalSourceRoot=options.numericalSourceRoot, ...
    sourceHEAD=strtrim(string(numericalHead)), ...
    matlabVersion=string(version), ...
    upstreamScreeningManifestPath=screeningManifestPath, ...
    upstreamScreeningManifestSHA256=sha256(screeningManifestPath), ...
    upstreamSourcePath=string(saved.sourcePath), ...
    upstreamSourceSHA256=string(saved.sourceSHA256), ...
    parameters=struct(grid=[256 256 129],forcing="WVNonlinearAdvection", ...
        initialTime=initialTime,finalTime=finalTime,initialStep=step, ...
        outputInterval=.5,denseOutputTimes=denseTime,fields={{"u"}}, ...
        particleX=[1900 11400],particleY=[1100 7700],particleZ=[-250 -750], ...
        tracer="dye"), ...
    capacityPreflight=struct(policy="refuse rather than substitute a smaller grid", ...
        minimumAuthoringFreeBytes=minimumFreeBytes,usableBytesBefore=usableBefore, ...
        hostPhysicalMemoryBytes=physicalMemoryBytes, ...
        groupedScientificArrayBytes=1.290598213672638*2^30, ...
        firstBlockFourOutputPayloadLowerBoundBytes=4*392274720), ...
    profiles={{profile}});
saveJSON(fullfile(folder,"manifest.json"),manifest);
end

function value = hostPhysicalMemoryBytes()
[status,text] = system("/usr/sbin/sysctl -n hw.memsize");
assert(status==0,"WaveVortexModel:FixtureCapacity", ...
    "Unable to read host physical-memory capacity.");
value = str2double(strtrim(text));
assert(isfinite(value) && value>0,"WaveVortexModel:FixtureCapacity", ...
    "Invalid host physical-memory capacity.");
end

function writeInitial(model,path,initialTime,finalTime,denseTime)
file = model.createNetCDFFileForModelOutput(path,outputInterval=.5, ...
    shouldOverwriteExisting=false);
defaultGroup = file.outputGroupWithName(model.defaultOutputGroupName());
particles = model.fluxedObservingSystemWithName("float");
tracer = model.fluxedObservingSystemWithName("dye");
defaultGroup.removeObservingSystem([particles tracer]);
dense = file.addNewEvenlySpacedOutputGroup("dense",outputInterval=.25, ...
    initialTime=denseTime,finalTime=denseTime);
dense.addObservingSystem(WVEulerianFields(model,fieldNames="u"));
particleGroup = file.addNewEvenlySpacedOutputGroup("particles",outputInterval=.5, ...
    initialTime=initialTime,finalTime=finalTime);
particleGroup.addObservingSystem(particles);
tracerGroup = file.addNewEvenlySpacedOutputGroup("tracers",outputInterval=.5, ...
    initialTime=initialTime,finalTime=finalTime);
tracerGroup.addObservingSystem(tracer);
file.outputTimesForIntegrationPeriod(initialTime,finalTime);
file.writeTimeStepToOutputFile(initialTime);
end

function value = sha256(path)
[status,text] = system("/usr/bin/shasum -a 256 "+shellQuote(path));
assert(status==0,"WaveVortexModel:FixtureHash","Unable to hash %s",path);
value = extractBefore(string(strtrim(text))," ");
end

function value = shellQuote(value)
value = "'"+replace(string(value),"'","'""'""'")+"'";
end

function saveJSON(path,value)
file = fopen(path,"w");
if file<0, error("WaveVortexModel:FixtureWrite","Unable to write %s",path); end
cleanup = onCleanup(@()fclose(file));
fwrite(file,jsonencode(value,PrettyPrint=true));
fwrite(file,newline);
end
